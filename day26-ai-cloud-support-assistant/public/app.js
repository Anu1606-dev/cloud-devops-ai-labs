const chatForm = document.getElementById("chat-form");
const queryInput = document.getElementById("query");
const sendButton = document.getElementById("send-button");
const messages = document.getElementById("messages");
const characterCount = document.getElementById("character-count");
const resultSection = document.getElementById("result-section");
const sourcesContainer = document.getElementById("sources");

queryInput.addEventListener("input", () => {
    characterCount.textContent = `${queryInput.value.length} / 500`;
});

function addMessage(role, content) {
    const article = document.createElement("article");
    article.className = `message ${role}`;

    const label = document.createElement("div");
    label.className = "message-label";
    label.textContent = role === "user" ? "YOU" : "ASSISTANT";

    const paragraph = document.createElement("p");
    paragraph.textContent = content;

    article.appendChild(label);
    article.appendChild(paragraph);
    messages.appendChild(article);

    messages.scrollTop = messages.scrollHeight;
}

function displaySources(sources) {
    sourcesContainer.replaceChildren();

    if (!Array.isArray(sources) || sources.length === 0) {
        const message = document.createElement("p");
        message.textContent = "No source documents were returned.";
        sourcesContainer.appendChild(message);
        return;
    }

    sources.forEach((source) => {
        const card = document.createElement("article");
        card.className = "source-card";

        const filename = document.createElement("p");
        filename.textContent = source.file || "Unknown document";

        const scoreElement = document.createElement("p");
        const similarity = Number(source.score);

        scoreElement.textContent = Number.isFinite(similarity)
            ? `Similarity score: ${similarity.toFixed(4)}`
            : "Similarity score unavailable";

        card.appendChild(filename);
        card.appendChild(scoreElement);
        sourcesContainer.appendChild(card);
    });
}

chatForm.addEventListener("submit", async (event) => {
    event.preventDefault();

    const query = queryInput.value.trim();

    if (!query) {
        addMessage("assistant", "Please enter a question before sending.");
        return;
    }

    addMessage("user", query);

    sendButton.disabled = true;
    sendButton.textContent = "Processing...";
    queryInput.disabled = true;

    resultSection.classList.add("hidden");

    try {
        const response = await fetch("/api/rag", {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({ query })
        });

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.error || "The API request failed.");
        }

        addMessage("assistant", data.answer || "No answer was returned.");

        if (data.model?.inference_performed === false) {
            addMessage(
                "assistant",
                "Demo notice: This answer was generated by the local mock adapter. No live LLM inference was performed."
            );
        }

        displaySources(data.sources);
        resultSection.classList.remove("hidden");

        queryInput.value = "";
        characterCount.textContent = "0 / 500";
    } catch (error) {
        addMessage(
            "assistant",
            `Unable to process your question: ${error.message}`
        );
    } finally {
        sendButton.disabled = false;
        sendButton.textContent = "Send question →";
        queryInput.disabled = false;
        queryInput.focus();
    }
});
